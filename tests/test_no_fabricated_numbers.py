"""Every \\newcommand number in paper/generated/numbers.tex must come from make_tables.py,
and the paper body must not contain hard-coded result numbers outside that file."""
import os
import re

ROOT = os.path.join(os.path.dirname(__file__), "..")


def test_paper_uses_macros_only():
    sec = os.path.join(ROOT, "paper", "sections")
    if not os.path.isdir(sec):
        return
    bad = []
    for f in os.listdir(sec):
        txt = open(os.path.join(sec, f)).read()
        # decimals like 0.873 in results sections are suspicious unless inside a macro definition
        if f.startswith(("05", "06", "07")):
            for m in re.finditer(r"(?<![\\\w{])0\.\d{2,}(?!\\(line|text)width)", txt):
                bad.append((f, m.group()))
    assert not bad, f"hard-coded numbers in results sections: {bad[:5]}"


def test_numbers_file_is_generated():
    p = os.path.join(ROOT, "paper", "generated", "numbers.tex")
    if os.path.exists(p):
        assert "AUTO-GENERATED by scripts/make_tables.py" in open(p).read()


def test_every_result_macro_is_defined():
    """Macros used in the paper that look like result macros must exist in numbers.tex."""
    p = os.path.join(ROOT, "paper", "generated", "numbers.tex")
    if not os.path.exists(p):
        return
    defined = set(re.findall(r"\\newcommand\{\\(\w+)\}", open(p).read()))
    prefixes = ("Dfeat", "DCR", "Skip", "Direct", "Diff", "Pval", "Trend", "Slope", "AblR", "NAfter", "NBefore",
                "NAt", "MinPerm", "Rbypass", "BypassFlip", "NHops", "NCert", "NModels", "MaxConserv", "StepOnly",
                "ISD", "RelMSE", "EtoE")
    missing = []
    for f in os.listdir(os.path.join(ROOT, "paper", "sections")):
        for name in re.findall(r"\\(\w+)", open(os.path.join(ROOT, "paper", "sections", f)).read()):
            if name.startswith(prefixes) and name not in defined and name != "Dfeat":
                missing.append((f, name))
    assert not missing, missing
