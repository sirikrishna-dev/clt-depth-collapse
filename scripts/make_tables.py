#!/usr/bin/env python
"""Aggregate result CSVs into summary tables + LaTeX macros for the paper.

    python scripts/make_tables.py --results results/merged [--paper paper/generated]

Writes results/<run>/summary_*.csv and paper/generated/{numbers.tex, tab_*.tex}.
Every number that appears in the paper comes from here; nothing is typed by hand.
"""
import argparse
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
from cdc.stats import bootstrap_ci, paired_signflip_p, holm, spearman_trend  # noqa: E402

WORD = {1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five", 6: "Six"}
KIND = {"plt": "PLT", "clt": "CLT", "plt_parammatched": "PLTpm"}


def macro(name, val, fmt="{:.2f}"):
    if isinstance(val, (int, np.integer)):
        s = str(int(val))
    elif val is None or (isinstance(val, float) and np.isnan(val)):
        s = "n/a"
    else:
        s = fmt.format(val)
    return f"\\newcommand{{\\{name}}}{{{s}}}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results/merged")
    ap.add_argument("--paper", default="paper/generated")
    ap.add_argument("--main-k", type=int, default=8)
    ap.add_argument("--metric", default="root_signed_D_feat",
                    help="headline depth metric column (see docs/hypotheses.md)")
    a = ap.parse_args()
    R = a.results
    os.makedirs(a.paper, exist_ok=True)
    M = ["% AUTO-GENERATED by scripts/make_tables.py -- do not edit by hand",
         f"% source: {R}"]

    # ---------------- certificates
    cert = pd.read_csv(os.path.join(R, "ground_truth_certificates.csv"))
    cs = cert.groupby("D").agg(n_models=("model", "count"), n_certified=("certified", "sum"),
                               clean=("clean_bit_acc", "mean"), iia_cf_min=("iia_cf_min", "min"),
                               strict_min=("strict_min", "min"), bypass_min=("bypass_min", "min"),
                               circuit_only=("circuit_only_acc", "min")).reset_index()
    cs.to_csv(os.path.join(R, "summary_certificates.csv"), index=False)  # min/mean over ALL trained models
    for D_, n_ in zip(cs.D, cs.n_certified):
        M.append(macro(f"NCert{WORD[int(D_)]}", int(n_)))
    M.append(macro("NModels", int(len(cert))))
    M.append(macro("NCertified", int(cert.certified.sum())))
    with open(os.path.join(a.paper, "tab_certificates.tex"), "w") as f:
        f.write("\\begin{tabular}{rrrrrrr}\\toprule\n$D$ & models & certified & clean acc & min IIA (cf) & min strict & min bypass-free\\\\\\midrule\n")
        for _, r in cs.iterrows():
            f.write(f"{int(r.D)} & {int(r.n_models)} & {int(r.n_certified)} & {r.clean:.3f} & {r.iia_cf_min:.3f} & {r.strict_min:.3f} & {r.bypass_min:.3f}\\\\\n")
        f.write("\\bottomrule\\end{tabular}\n")

    # ---------------- fidelity
    fid = pd.read_csv(os.path.join(R, "replacement_fidelity.csv"))
    fs = fid.groupby(["D", "kind", "k"]).agg(rel_mse=("rel_mse_mean", "mean"), e2e_acc=("e2e_bit_acc", "mean"),
                                             e2e_kl=("e2e_kl", "mean"), n_params=("n_params", "mean"),
                                             n_features=("n_features", "mean")).reset_index()
    fs.to_csv(os.path.join(R, "summary_fidelity.csv"), index=False)
    M.append(macro("RelMSEMax", float(fs.rel_mse.max()), "{:.4f}"))
    M.append(macro("EtoEAccMin", float(fs.e2e_acc.min()), "{:.3f}"))
    with open(os.path.join(a.paper, "tab_fidelity.tex"), "w") as f:
        f.write("\\begin{tabular}{rlrrrrr}\\toprule\n$D$ & replacement & $k$ & features/layer & params & rel. MSE & e2e acc\\\\\\midrule\n")
        for _, r in fs.iterrows():
            f.write(f"{int(r.D)} & {KIND.get(r.kind, r.kind)} & {int(r.k)} & {int(r.n_features)} & {int(r.n_params)} & {r.rel_mse:.4f} & {r.e2e_acc:.3f}\\\\\n")
        f.write("\\bottomrule\\end{tabular}\n")

    # ---------------- depth (per tc = mean over examples; seeds are the unit)
    g = pd.read_csv(os.path.join(R, "graph_metrics_per_example.csv"))
    M.append(macro("MaxConservationErr", float(g.conservation_err.max()), "{:.1e}"))
    cols = [c for c in g.columns if pd.api.types.is_numeric_dtype(g[c]) and c not in ("example", "seed", "D", "n_layers", "k")]
    per_tc = g.groupby(["tc", "model", "D", "n_layers", "seed", "kind", "k"])[cols].mean().reset_index()
    per_tc["DCR"] = per_tc[a.metric] / per_tc.D
    per_tc["depth_loss"] = per_tc.D - per_tc[a.metric]
    per_tc.to_csv(os.path.join(R, "summary_depth_per_model.csv"), index=False)
    rows = []
    main = per_tc[(per_tc.k == a.main_k) & (per_tc.n_layers == per_tc.D)]
    for (D, kind), d in main.groupby(["D", "kind"]):
        r = {"D": D, "kind": kind, "n_seeds": len(d)}
        for col in (a.metric, "root_D_feat", "DCR", "skip_mass", "root_signed_direct_frac", "error_influence"):
            m, lo, hi = bootstrap_ci(d[col])
            r.update({col: m, col + "_lo": lo, col + "_hi": hi})
        for h in range(1, int(D)):
            if f"IMF_h{h}" in d:
                r[f"IMF_h{h}"] = d[f"IMF_h{h}"].mean()
        rows.append(r)
    ds = pd.DataFrame(rows)
    # paired CLT vs PLT on the same base model
    pv = []
    for D in sorted(main.D.unique()):
        p_ = main[(main.D == D) & (main.kind == "plt")].set_index("model")[a.metric]
        c_ = main[(main.D == D) & (main.kind == "clt")].set_index("model")[a.metric]
        common = p_.index.intersection(c_.index)
        pv.append({"D": D, "mean_diff_clt_minus_plt": float((c_[common] - p_[common]).mean()) if len(common) else np.nan,
                   "p_signflip": paired_signflip_p(c_[common], p_[common]) if len(common) else np.nan,
                   "n_pairs": len(common)})
    pv = pd.DataFrame(pv)
    if len(pv):
        pv["p_holm"] = holm(pv.p_signflip.fillna(1).values)
    ds.to_csv(os.path.join(R, "summary_depth.csv"), index=False)
    pv.to_csv(os.path.join(R, "summary_depth_paired_tests.csv"), index=False)
    for _, r in ds.iterrows():
        n = f"{KIND.get(r.kind, r.kind)}D{WORD[int(r.D)]}"
        M += [macro(f"Dfeat{n}", r[a.metric]), macro(f"DfeatLo{n}", r[a.metric + "_lo"]),
              macro(f"DfeatHi{n}", r[a.metric + "_hi"]), macro(f"DCR{n}", r.DCR),
              macro(f"Skip{n}", r.skip_mass), macro(f"Direct{n}", r.root_signed_direct_frac)]
    for _, r in pv.iterrows():
        M += [macro(f"DiffCLTPLTD{WORD[int(r.D)]}", r.mean_diff_clt_minus_plt),
              macro(f"PvalD{WORD[int(r.D)]}", r.p_signflip, "{:.3f}")]
    # trend of depth loss with D
    for kind in main.kind.unique():
        d = main[main.kind == kind]
        if d.D.nunique() >= 3:
            rho, p = spearman_trend(d.D, d.depth_loss)
            M += [macro(f"TrendRho{KIND.get(kind, kind)}", rho), macro(f"TrendP{KIND.get(kind, kind)}", p, "{:.3g}")]
    # slope difference (CLT - PLT) of depth loss vs D, bootstrap over models
    slopes = {}
    for kind in ("plt", "clt"):
        d = main[main.kind == kind]
        if d.D.nunique() >= 2:
            slopes[kind] = np.polyfit(d.D, d.depth_loss, 1)[0]
    if len(slopes) == 2:
        M.append(macro("SlopeDiffCLTminusPLT", slopes["clt"] - slopes["plt"]))
    with open(os.path.join(a.paper, "tab_depth.tex"), "w") as f:
        f.write("\\begin{tabular}{rlrrrrr}\\toprule\n$D$ & repl. & seeds & $D_\\mathrm{feat}$ [95\\% CI] & DCR & skip mass & direct frac.\\\\\\midrule\n")
        for _, r in ds.iterrows():
            f.write(f"{int(r.D)} & {KIND.get(r.kind, r.kind)} & {int(r.n_seeds)} & {r[a.metric]:.2f} [{r[a.metric+'_lo']:.2f}, {r[a.metric+'_hi']:.2f}] & {r.DCR:.2f} & {r.skip_mass:.2f} & {r.root_signed_direct_frac:.2f}\\\\\n")
        f.write("\\bottomrule\\end{tabular}\n")

    # ---------------- skip dependence
    p = os.path.join(R, "skip_dependence.csv")
    if os.path.exists(p):
        sd = pd.read_csv(p)
        sds = sd.groupby(["D", "kind", "k"])[["full_route_acc", "stepwise_only_acc", "skip_only_acc", "ISD"]].mean().reset_index()
        sds.to_csv(os.path.join(R, "summary_skip_dependence.csv"), index=False)
        for _, r in sds[sds.k == a.main_k].iterrows():
            n = f"{KIND.get(r.kind, r.kind)}D{WORD[int(r.D)]}"
            M += [macro(f"SkipOnly{n}", r.skip_only_acc), macro(f"StepOnly{n}", r.stepwise_only_acc),
                  macro(f"ISD{n}", r.ISD, "{:.3f}")]
    # ---------------- ablation check (graph-predicted vs actual)
    p = os.path.join(R, "ablation_check.csv")
    if os.path.exists(p):
        ab = pd.read_csv(p)
        rr = []
        for kind, d in ab.groupby("kind"):
            r = np.corrcoef(d.pred, d.actual)[0, 1] if len(d) > 2 else np.nan
            rr.append({"kind": kind, "pearson_r": r, "n": len(d)})
            M.append(macro(f"AblR{KIND.get(kind, kind)}", r))
        pd.DataFrame(rr).to_csv(os.path.join(R, "summary_ablation_check.csv"), index=False)
    # ---------------- 2x2 decodable x causal
    p = os.path.join(R, "probes_causal_2x2.csv")
    if os.path.exists(p):
        pr = pd.read_csv(p)
        pr["relation"] = np.where(pr.p == pr.hop, "at site", np.where(pr.p < pr.hop, "before site", "after site"))
        tab = pr.groupby(["relation", "decodable", "causal"]).size().reset_index(name="n")
        tab.to_csv(os.path.join(R, "summary_2x2.csv"), index=False)
        after = pr[pr.relation == "after site"]
        M.append(macro("NAfterDecodable", int(after.decodable.sum())))
        M.append(macro("NAfterDecodableCausal", int((after.decodable & after.causal).sum())))
        before = pr[pr.relation == "before site"]
        M.append(macro("NBeforeDecodable", int(before.decodable.sum())))
        M.append(macro("NBeforeDecodableCausal", int((before.decodable & before.causal).sum())))
        M.append(macro("NAfterCausal", int(after.causal.sum())))
        at = pr[pr.relation == "at site"]
        M.append(macro("NAtSite", int(len(at))))
        M.append(macro("NAtSiteBoth", int((at.decodable & at.causal).sum())))
        M.append(macro("MinPermP", float(pr.perm_p.min()), "{:.4f}"))
    # ---------------- logit-level bypass (original vs replacement models)
    p = os.path.join(R, "logit_level_bypass.csv")
    if os.path.exists(p):
        lb = pd.read_csv(p)
        per_model = lb.groupby(["model", "D", "system"]).r_bypass.mean().reset_index()
        lbs = per_model.groupby(["D", "system"]).r_bypass.agg(["mean", "min", "max", "count"]).reset_index()
        lbs.to_csv(os.path.join(R, "summary_logit_bypass.csv"), index=False)
        SYS = {"original": "Orig", "plt": "PLT", "clt": "CLT"}
        for _, r in lbs.iterrows():
            M.append(macro(f"Rbypass{SYS[r.system]}D{WORD[int(r.D)]}", r["mean"]))
        for sysn in ("original", "plt", "clt"):
            d = lb[lb.system == sysn]
            M.append(macro(f"RbypassAll{SYS[sysn]}", d.r_bypass.mean()))
            M.append(macro(f"BypassFlipMax{SYS[sysn]}", d.bypass_sign_flip_rate.max(), "{:.3f}"))
        # CLT > PLT pairs (same model, same hop)
        pv_ = lb.pivot_table(index=["model", "hop"], columns="system", values="r_bypass")
        if {"plt", "clt"} <= set(pv_.columns):
            M.append(macro("NHopsCLTgtPLT", int((pv_.clt > pv_.plt).sum())))
            M.append(macro("NHopsTotal", int(len(pv_))))
        with open(os.path.join(a.paper, "tab_logit_bypass.tex"), "w") as f:
            f.write("\\begin{tabular}{rrrr}\\toprule\n$D$ & original & PLT & CLT\\\\\\midrule\n")
            for D in sorted(lbs.D.unique()):
                v = {r.system: r["mean"] for _, r in lbs[lbs.D == D].iterrows()}
                f.write(f"{int(D)} & {v.get('original', np.nan):.3f} & {v.get('plt', np.nan):.3f} & {v.get('clt', np.nan):.3f}\\\\\n")
            f.write("\\bottomrule\\end{tabular}\n")
    # ---------------- naive patching
    p = os.path.join(R, "naive_patching.csv")
    if os.path.exists(p):
        nv = pd.read_csv(p)
        nvs = nv.groupby(["D", "hop", "hypothesis"]).agreement_flip.mean().reset_index()
        nvs.to_csv(os.path.join(R, "summary_naive_patching.csv"), index=False)
    with open(os.path.join(a.paper, "numbers.tex"), "w") as f:
        f.write("\n".join(M) + "\n")
    print("\n".join(M))


if __name__ == "__main__":
    main()
