#!/usr/bin/env python
"""Real-data (GPT-2 two-hop) macros and table for paper Sec. 7.

    python scripts/make_lm_tables.py --results results/lm_twohop --paper paper/generated
    python scripts/make_lm_tables.py --placeholder --paper paper/generated   # before the Colab run

Writes paper/generated/numbers_lm.tex and tab_lm_validation.tex. With --placeholder every
macro prints a bold "??" so the paper compiles but no number can be mistaken for a result.
"""
import argparse
import os

import pandas as pd

NAMES = {"plt": "PLT", "clt": "CLT"}
QTY = {
    ("V1_depth_sensitivity", "D_feat(2hop) - D_feat(1hop), per state"): "VOne",
    ("V2_causal_specificity", "logit drop: state features - random features"): "VTwo",
    ("V3_graph_vs_intervention", "Spearman(IMF, ablation drop)"): "VThree",
}


def fmt(x, d=2):
    return "--" if pd.isna(x) else f"{x:.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results/lm_twohop")
    ap.add_argument("--paper", default="paper/generated")
    ap.add_argument("--placeholder", action="store_true")
    a = ap.parse_args()
    os.makedirs(a.paper, exist_ok=True)
    macros = {}
    keys = ["LMNTwoHop", "LMNOneHop", "LMModel"]
    for v in QTY.values():
        for k in NAMES.values():
            keys += [f"LM{v}{k}", f"LM{v}Lo{k}", f"LM{v}Hi{k}", f"LM{v}P{k}"]
    for k in NAMES.values():
        keys += [f"LMDfeatTwo{k}", f"LMDfeatOne{k}", f"LMNMSE{k}", f"LMErrInfl{k}", f"LMTopKept{k}"]
    keys += ["LMDfeatDiffCLTminusPLT", "LMDfeatDiffP"]

    if a.placeholder:
        macros = {k: r"\textbf{??}" for k in keys}
        rows_tex = r"\multicolumn{5}{c}{\textbf{not run yet: run notebooks/02 and regenerate}}\\"
    else:
        R = a.results
        pr = pd.read_csv(os.path.join(R, "prompts.csv"))
        t = pd.read_csv(os.path.join(R, "lm_validation_tests.csv"))
        g = pd.read_csv(os.path.join(R, "lm_twohop_graph_metrics.csv"))
        fid = pd.read_csv(os.path.join(R, "lm_fidelity.csv"))
        import json
        args = json.load(open(os.path.join(R, "args.json")))
        macros["LMModel"] = args["model"].replace("_", r"\_")
        macros["LMNTwoHop"] = str(int((pr.kept & (pr.hop == "2hop")).sum()))
        macros["LMNOneHop"] = str(int((pr.kept & (pr.hop == "1hop")).sum()))
        for (test, qty), v in QTY.items():
            for kind, K in NAMES.items():
                r = t[(t.test == test) & (t.quantity == qty) & (t.kind == kind)]
                r = r.iloc[0] if len(r) else None
                macros[f"LM{v}{K}"] = fmt(None if r is None else r["mean"])
                macros[f"LM{v}Lo{K}"] = fmt(None if r is None else r["ci_lo"])
                macros[f"LM{v}Hi{K}"] = fmt(None if r is None else r["ci_hi"])
                macros[f"LM{v}P{K}"] = fmt(None if r is None else r["p_signflip"], 3)
        for kind, K in NAMES.items():
            d = g[g.kind == kind]
            macros[f"LMDfeatTwo{K}"] = fmt(d[d.hop == "2hop"].root_signed_D_feat.mean())
            macros[f"LMDfeatOne{K}"] = fmt(d[d.hop == "1hop"].root_signed_D_feat.mean())
            macros[f"LMErrInfl{K}"] = fmt(d.error_influence.mean())
            macros[f"LMTopKept{K}"] = fmt(d.orig_top1_kept.mean())
            f = fid[fid.kind == kind]
            macros[f"LMNMSE{K}"] = fmt(f.heldout_nmse_mean.iloc[0] if len(f) else None, 3)
        r = t[(t.test == "V4_clt_minus_plt") & (t.kind == "2hop") & (t.quantity == "root_signed_D_feat")]
        macros["LMDfeatDiffCLTminusPLT"] = fmt(r["mean"].iloc[0] if len(r) else None)
        macros["LMDfeatDiffP"] = fmt(r["p_signflip"].iloc[0] if len(r) else None, 3)
        lines = []
        for _, r in t.iterrows():
            lines.append(f"{r.test.replace('_', ' ')} & {r.kind} & {r.quantity.replace('_', ' ')} & "
                         f"{fmt(r['mean'])} [{fmt(r.ci_lo)}, {fmt(r.ci_hi)}] & {fmt(r.p_signflip, 3)} (n={int(r.n)})\\\\")
        rows_tex = "\n".join(lines)

    with open(os.path.join(a.paper, "numbers_lm.tex"), "w") as fh:
        fh.write("% AUTO-GENERATED by scripts/make_lm_tables.py -- do not edit by hand\n")
        fh.write(f"% source: {'PLACEHOLDER (not run)' if a.placeholder else a.results}\n")
        for k in keys:
            fh.write(f"\\newcommand{{\\{k}}}{{{macros.get(k, '--')}}}\n")
    with open(os.path.join(a.paper, "tab_lm_validation.tex"), "w") as fh:
        fh.write("% AUTO-GENERATED by scripts/make_lm_tables.py\n")
        fh.write("\\begin{table}[t]\\centering\\scriptsize\n\\caption{Real-data validation on two-hop factual "
                 "recall. Mean [95\\% bootstrap CI]; sign-flip $p$.}\\label{tab:lm}\n")
        fh.write("\\begin{tabular}{llp{3.6cm}ll}\\toprule\nTest & Kind/hop & Quantity & Mean [CI] & $p$ (n)\\\\\\midrule\n")
        fh.write(rows_tex + "\n\\bottomrule\\end{tabular}\\end{table}\n")
    print("wrote", os.path.join(a.paper, "numbers_lm.tex"), "and tab_lm_validation.tex")


if __name__ == "__main__":
    main()
